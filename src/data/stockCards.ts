export const STOCK_CARD_BY_ID = Object.fromEntries(
  STOCK_CARDS.map((card) => [card.id, card])
) as Record<string, TradeCard>;

export function getStockCard(cardId: string): TradeCard {
  if (cardId === NOISE_GLITCH_CARD.id) return NOISE_GLITCH_CARD;

  const card = STOCK_CARD_BY_ID[cardId];

  if (!card) {
    throw new Error(`Unknown trade card: ${cardId}`);
  }

  return card;
}




